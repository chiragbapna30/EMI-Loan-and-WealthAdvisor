def compute_emi(amount: float, rate_annual: float, months: int) -> Dict[str, Any]:
    """
    Computes monthly EMI and total interest for a given loan amount, 
    annual interest rate (%), and tenure in months.
    """
    if months <= 0 or amount <= 0:
        return {"error": "Amount and months must be greater than 0."}
    
    r = (rate_annual / 100) / 12  # Monthly interest rate
    
    if r == 0:
        emi = amount / months
        total_payment = amount
        total_interest = 0.0
    else:
        # Standard EMI Formula: P * r * (1+r)^n / ((1+r)^n - 1)
        pow_factor = math.pow(1 + r, months)
        emi = amount * r * pow_factor / (pow_factor - 1)
        total_payment = emi * months
        total_interest = total_payment - amount

    return {
        "amount": round(amount, 2),
        "rate_annual": rate_annual,
        "months": months,
        "emi": round(emi, 2),
        "total_payment": round(total_payment, 2),
        "total_interest": round(total_interest, 2)
    }


def compare_options(options: List[Dict[str, Any]], monthly_income: Optional[float] = None) -> Dict[str, Any]:
    """
    Compares multiple loan EMI options, evaluates total interest differences,
    and identifies which options are affordable based on a 40% income rule.
    """
    if not options:
        return {"error": "No options provided for comparison."}
    
    evaluated = []
    recommended_option = None
    lowest_interest_option = min(options, key=lambda x: x.get("total_interest", float('inf')))

    for opt in options:
        emi = opt.get("emi", 0)
        affordable = True
        affordability_note = "Income not provided."

        if monthly_income and monthly_income > 0:
            # Rule: EMI should ideally be <= 40% of net monthly income
            emi_to_income_ratio = (emi / monthly_income) * 100
            affordable = emi_to_income_ratio <= 40.0
            affordability_note = (
                f"EMI is {round(emi_to_income_ratio, 1)}% of income. "
                + ("Affordable (<=40%)." if affordable else "Unaffordable (>40%).")
            )

        evaluated.append({
            "loan_details": opt,
            "affordable": affordable,
            "note": affordability_note
        })

        if affordable and (recommended_option is None or opt["emi"] < recommended_option["emi"]):
            recommended_option = opt

    return {
        "compared_options": evaluated,
        "lowest_interest_option": lowest_interest_option,
        "recommended_option": recommended_option if recommended_option else "None fit the 40% affordability threshold."
    }


